/** Returns the full local university dataset (no backend/network call required) */
export function getAllUniversities() {
  return UNIVERSITY_DATASET;
}

/** Returns a single university by its id, or undefined if not found */
export function getUniversityById(id) {
  return UNIVERSITY_DATASET.find((u) => String(u.id) === String(id));
}

/** Returns all unique Master's program titles across the dataset, sorted alphabetically */
export function getUniqueMasterPrograms() {
  const all = UNIVERSITY_DATASET.flatMap((u) => u.offered_majors || []);
  return [...new Set(all)].sort();
}

/** Returns universities filtered by target countries (or all if no filter) */
export function getUniversitiesByCountries(countries) {
  if (!countries || countries.length === 0) return UNIVERSITY_DATASET;
  return UNIVERSITY_DATASET.filter((u) => countries.includes(u.country));
}